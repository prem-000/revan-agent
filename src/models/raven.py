from __future__ import annotations

import hashlib
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class IntentType(str, Enum):
    IDEA = "idea"
    PROJECT = "project"


class FreshnessState(str, Enum):
    FRESH = "fresh"
    AGING = "aging"
    STALE = "stale"
    UNKNOWN = "unknown"


class VerificationState(str, Enum):
    VERIFIED = "verified"
    UNVERIFIED = "unverified"
    DISPUTED = "disputed"
    UNREACHABLE = "unreachable"
    REJECTED = "rejected"


class ProjectInspection(BaseModel):
    """Metadata extracted safely from a local project directory."""
    root_path: str
    is_valid: bool = True
    detected_stack: List[str] = Field(default_factory=list)
    structure_summary: str = ""
    manifest_files: List[str] = Field(default_factory=list)
    dependencies: List[str] = Field(default_factory=list)
    risks_and_gaps: List[str] = Field(default_factory=list)
    error_message: Optional[str] = None


class AnalysisResult(BaseModel):
    """Output from the Analyzer node."""
    intent: IntentType = IntentType.IDEA
    goal: str
    constraints: List[str] = Field(default_factory=list)
    assumptions: List[str] = Field(default_factory=list)
    unknowns: List[str] = Field(default_factory=list)
    project_inspection: Optional[ProjectInspection] = None
    domain_anchor: Optional[str] = None
    disambiguated_terms: Dict[str, str] = Field(default_factory=dict)
    is_concept_query: bool = False


class ResearchObjective(BaseModel):
    """A concrete objective produced by the Planner."""
    id: str
    description: str
    questions: List[str] = Field(default_factory=list)
    acceptance_criteria: List[str] = Field(default_factory=list)
    assigned_tunnels: List[str] = Field(
        default_factory=lambda: ["github", "documentation", "papers", "web", "community"]
    )
    freshness_requirement: FreshnessState = FreshnessState.UNKNOWN


class ResearchPlan(BaseModel):
    """The master research plan."""
    profile: str = "standard"  # fast, standard, deep
    objectives: List[ResearchObjective] = Field(default_factory=list)
    is_approved: bool = True
    approval_policy: str = "auto"  # auto or manual
    revision_count: int = 0


class EvidenceItem(BaseModel):
    """A normalized, verifiable piece of evidence with full provenance."""
    evidence_id: str
    source_type: str  # github, documentation, papers, web, community, local_project
    canonical_url: str
    title: str = ""
    publisher_or_repo: str = ""
    published_date: Optional[str] = None
    updated_date: Optional[str] = None
    discovered_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    checked_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    excerpt: str
    location: Optional[str] = None  # line range, page number, url fragment
    objective_id: str = ""
    objective_ids: List[str] = Field(default_factory=list)
    verification_state: VerificationState = VerificationState.UNVERIFIED
    verification_notes: str = ""
    freshness_state: FreshnessState = FreshnessState.UNKNOWN
    reachable: bool = True
    relevance_score: float = 1.0
    relevance_reason: str = ""
    content_hash: str = ""
    extraction_method: str = "search_snippet"  # http, playwright, github_api, local_ast, search_snippet
    extracted_text_ref: Optional[str] = None  # reference to bounded content store
    repository_meta: Optional[Dict[str, Any]] = None  # stars, forks, language, license, release
    resource_explanation: Optional[Dict[str, str]] = None  # what_it_is, what_it_provides, technical_details, recommendation, limitations

    def model_post_init(self, __context: Any) -> None:
        if self.objective_id and not self.objective_ids:
            self.objective_ids = [self.objective_id]
        elif self.objective_ids and not self.objective_id:
            self.objective_id = self.objective_ids[0]

    @classmethod
    def compute_hash(cls, canonical_url: str, excerpt: str) -> str:
        raw = f"{canonical_url.strip().lower()}||{excerpt.strip()}".encode("utf-8")
        return hashlib.sha256(raw).hexdigest()[:16]


class SourceTunnelResult(BaseModel):
    """Result of running an individual source tunnel."""
    tunnel_name: str
    status: str  # "completed", "failed", "disabled", "skipped"
    items: List[EvidenceItem] = Field(default_factory=list)
    error: Optional[str] = None
    reason: Optional[str] = None


class CritiqueGap(BaseModel):
    objective_id: str
    description: str
    severity: str = "material"  # blocker, material, minor
    suggested_tunnel: str = "web"


class CritiqueReport(BaseModel):
    """Report generated by the Critic assessing coverage and evidence."""
    coverage_score: float = 0.0
    unresolved_gaps: List[CritiqueGap] = Field(default_factory=list)
    contradictions: List[str] = Field(default_factory=list)
    risks: List[str] = Field(default_factory=list)
    should_continue: bool = False
    reason: str = ""


class FinalRavenReport(BaseModel):
    """The synthesized final report strictly grounded in verified evidence."""
    title: str = "Technical Intelligence Report"
    direct_answer: str = ""
    detailed_explanation: str = ""
    key_findings: List[str] = Field(default_factory=list)
    practical_guidance: List[str] = Field(default_factory=list)
    limitations_and_uncertainty: List[str] = Field(default_factory=list)
    executive_summary: str = ""
    findings_by_objective: Dict[str, str] = Field(default_factory=dict)
    sourced_facts: List[str] = Field(default_factory=list)
    inferences: List[str] = Field(default_factory=list)
    recommendations: List[str] = Field(default_factory=list)
    unknowns_and_limitations: List[str] = Field(default_factory=list)
    failed_tunnels: List[str] = Field(default_factory=list)
    stop_reason: str = "Completed"
    run_status: str = "completed"  # "completed" | "partial" | "failed"
    evidence_citations: List[Dict[str, Any]] = Field(default_factory=list)
    formatted_markdown: str = ""


class ClaimItem(BaseModel):
    claim_text: str
    cited_evidence_ids: List[str] = Field(default_factory=list)


class DraftAnswer(BaseModel):
    """Short answer draft composed of 2-4 sentences citing evidence IDs."""
    text: str
    sentences: List[str] = Field(default_factory=list)
    claims: List[ClaimItem] = Field(default_factory=list)
    cited_evidence_ids: List[str] = Field(default_factory=list)
    is_hedged_fallback: bool = False


class SelfCheckVerdict(BaseModel):
    """Result of self-check evaluation on a draft answer."""
    passed: bool
    unsupported_claims: List[str] = Field(default_factory=list)
    contradicted_claims: List[str] = Field(default_factory=list)
    overclaiming: List[str] = Field(default_factory=list)
    suggested_revision: Optional[str] = None
    reason: str = ""


class AnswerEvaluationMetrics(BaseModel):
    """Evaluation metrics for the answer quality."""
    length_ok: bool
    sentence_count: int
    citation_density: float  # citations per sentence
    citation_density_ok: bool
    zero_hallucinated_citations: bool
    self_check_passed: bool
    overall_quality_score: float

